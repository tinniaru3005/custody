"""Public-demo mode (``CUSTODY_PUBLIC_DEMO=true``): safe to expose without authentication.

This is NOT an auth system. It reduces the public surface to one synthetic tenant that
visitors can read and reset, nothing else:

- exactly one tenant (``CUSTODY_DEMO_TENANT``, default ``acme``); every other tenant path
  answers 404;
- read-only: only GET/HEAD/OPTIONS are allowed, plus ``POST
  /tenants/<demo>/console/demo/reset``, which restores the initial demo state
  deterministically (same ids, same graph) and is rate-limited;
- blocked: every Recorder write, Guard check/approve/reject/endorse, running scenarios,
  the Warden (it can call a paid LLM API) and sending disclosures;
- no server configuration is exposed: ``/swagger``, ``/redoc`` and ``/openapi.json`` are off,
  and ``/health`` reports only status, version and the demo tenant;
- the demo data is synthetic and its "secrets" are fake values generated by a simulated
  vault; raw values never reach the graph.

Deploy it with its own FalkorDB (or the embedded one); never point a public demo at a
database that holds real tenants.
"""
from __future__ import annotations

import json
import re
import threading
import time
from typing import Optional

PUBLIC_METHODS = {"GET", "HEAD", "OPTIONS"}
_TENANT_PATH = re.compile(r"^/tenants/([^/]+)(/.*)?$")
_SCHEMA_ROOTS = ("/swagger", "/redoc", "/openapi.json")  # FastAPI's API reference + schema
_API_ROOTS = ("/tenants", "/health") + _SCHEMA_ROOTS


def reset_path(tenant: str) -> str:
    return f"/tenants/{tenant}/console/demo/reset"


class PublicDemoGuard:
    """ASGI middleware enforcing the public-demo rules (runs after /api is stripped)."""

    def __init__(self, app, tenant: str) -> None:
        self.app = app
        self.tenant = tenant

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)
        method = scope.get("method", "GET").upper()
        path = scope.get("path", "")
        status, detail = self.decide(method, path)
        if status is None:
            return await self.app(scope, receive, send)
        body = json.dumps({"detail": detail}).encode()
        await send({"type": "http.response.start", "status": status,
                    "headers": [(b"content-type", b"application/json"),
                                (b"content-length", str(len(body)).encode())]})
        await send({"type": "http.response.body", "body": body})

    def decide(self, method: str, path: str):
        """(status, detail) to refuse the request, or (None, None) to let it through."""
        if path.startswith(_SCHEMA_ROOTS):
            return 404, "not found"
        m = _TENANT_PATH.match(path)
        if m:
            if m.group(1) != self.tenant:
                return 404, "not found"
            if method in PUBLIC_METHODS:
                return None, None
            if method == "POST" and path == reset_path(self.tenant):
                return None, None
            return 403, ("public demo is read-only; use Reset Demo to restore the initial "
                         "state")
        if method not in PUBLIC_METHODS and path.startswith(_API_ROOTS):
            return 403, "public demo is read-only"
        if method not in PUBLIC_METHODS:
            return 405, "method not allowed"
        return None, None


class ResetLimiter:
    """At most one reset per ``min_interval_s`` (resets drop and rebuild the graph)."""

    def __init__(self, min_interval_s: float) -> None:
        self.min_interval_s = min_interval_s
        self._last: Optional[float] = None
        self._lock = threading.Lock()

    def try_acquire(self) -> Optional[float]:
        """None if allowed (and records the reset); else seconds to wait."""
        with self._lock:
            now = time.monotonic()
            if self._last is not None and now - self._last < self.min_interval_s:
                return round(self.min_interval_s - (now - self._last), 1)
            self._last = now
            return None
